import {test,expect,declineOptionalCookies} from './public-fixture'
test('a guest route recovers after reload and blocks stale copy',async({page},info)=>{
 test.skip(!['desktop','phone-390'].includes(info.project.name),'Public route recovery on desktop and phone')
 await page.goto('/new-zealand/north-island#trip-planner');await declineOptionalCookies(page)
 await page.getByRole('spinbutton',{name:'Number of days',exact:true}).fill('7')
 await page.getByRole('button',{name:/Suggest my itineraries|Update my suggestions/}).click()
 await page.getByText('Copy or review the complete itinerary text',{exact:true}).click()
 await expect(page.getByRole('textbox',{name:'Itinerary text to copy',exact:true})).toHaveValue(/7 days \/ 6 nights/)
 await page.getByRole('spinbutton',{name:'Number of days',exact:true}).fill('6')
 await expect(page.getByRole('button',{name:'Copy itinerary',exact:true})).toBeDisabled()
 await expect(page.getByRole('textbox',{name:'Itinerary text to copy',exact:true})).toHaveValue(/Rebuild before copying/)
 await page.reload();await expect(page.getByRole('spinbutton',{name:'Number of days',exact:true})).toHaveValue('6')
 await page.getByRole('button',{name:'Update my suggestions',exact:true}).click()
 await page.getByText('Copy or review the complete itinerary text',{exact:true}).click()
 await expect(page.getByRole('textbox',{name:'Itinerary text to copy',exact:true})).toHaveValue(/6 days \/ 5 nights/)
 await page.reload();await page.getByText('Copy or review the complete itinerary text',{exact:true}).click()
 await expect(page.getByRole('textbox',{name:'Itinerary text to copy',exact:true})).toHaveValue(/6 days \/ 5 nights/)
})

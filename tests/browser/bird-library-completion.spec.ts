import {test,expect,declineOptionalCookies} from './public-fixture'
test.beforeEach(({},info)=>test.skip(!['desktop','phone-390'].includes(info.project.name),'Shared completion on desktop and phone'))
test('map fullscreen and Map/Place state survive country and island changes',async({page})=>{
 await page.goto('/');await declineOptionalCookies(page)
 await page.getByRole('button',{name:'Open map full screen',exact:true}).click()
 let map=page.locator('dialog[data-aves-map][data-expanded]');await expect(map).toBeVisible()
 await expect(page.locator('dialog[data-expanded]:not([data-aves-map])')).toHaveCount(0)
 const surface=await map.locator('[data-map-surface]').boundingBox(),stage=await map.locator('[data-map-view]').boundingBox();expect(stage!.height).toBeGreaterThanOrEqual(surface!.height-2)
 const destination=map.getByRole('button',{name:'Show New Zealand birds',exact:true});await destination.focus();await destination.press('Enter')
 const mapTab=map.getByRole('button',{name:'Map',exact:true});if(await mapTab.isVisible())await mapTab.click()
 await map.getByRole('combobox').filter({has:page.locator('option[value="south-island"]')}).selectOption('south-island')
 map=page.locator('dialog[data-aves-map][data-expanded]');await expect(map).toHaveAttribute('aria-label','South Island explorer map')
 await expect(map.getByRole('button',{name:'Close expanded South Island explorer map',exact:true})).toBeInViewport()
 await map.getByRole('button',{name:'Zoom ecosystem map out',exact:true}).click()
 await expect(page.locator('dialog[data-aves-map][data-expanded]')).toHaveAttribute('aria-label','Destination explorer map')
 await page.keyboard.press('Escape');await expect(page.locator('dialog[data-aves-map][data-expanded]')).toHaveCount(0)
})
test('photo-sized bird face retains album thumbnails, a compact audio control and eBird access',async({page})=>{
 await page.goto('/?explore=colombia');await declineOptionalCookies(page)
 await page.getByRole('button',{name:'Turn to the birds',exact:true}).click()
 const photo=page.locator('[data-carousel-image]:visible').first();await expect(photo.locator('img')).toBeVisible()
 const d=await photo.evaluate(e=>{const b=e.getBoundingClientRect();return{width:b.width,height:b.height,aspect:getComputedStyle(e).getPropertyValue('--bird-photo-aspect')}})
 const [w,h]=d.aspect.split('/').map(Number);expect(Math.abs(d.width/d.height-w/h)).toBeLessThan(.04)
 const follow=page.getByRole('button',{name:'Follow bird calls',exact:true});await expect(follow).toBeVisible();await expect(follow).toHaveText('')
 await page.getByRole('button',{name:'Species details & credits',exact:true}).click()
 await expect(page.getByRole('link',{name:'Explore on eBird',exact:true})).toHaveAttribute('href',/^https:\/\/ebird.org\/species\/[a-z0-9]+$/)
})

import { test, expect, declineOptionalCookies } from "./public-fixture"

test("landscape credits and expanded photographs return focus, scroll and the selected image", async ({ page }, info) => {
  test.skip(!["desktop", "phone-390"].includes(info.project.name), "Media overlay journeys use desktop and phone; map dismissal uses every project.")
  await page.goto("/new-zealand/north-island")
  await declineOptionalCookies(page)
  const gallery = page.locator("#place-gallery")
  const photo = gallery.locator("[data-place-image] img")
  const src = await photo.getAttribute("src")
  const expand = gallery.getByRole("button", { name: "Expand New Zealand landscapes", exact: true })
  await expand.scrollIntoViewIfNeeded()
  const scroll = await page.evaluate(() => scrollY)
  await expand.click()
  const dialog = page.getByRole("dialog", { name: "New Zealand landscapes", exact: true })
  await expect(dialog).toBeVisible()
  const credit = dialog.locator('summary[aria-label^="Photo credits:"]')
  await credit.click()
  await expect(dialog.getByRole("region", { name: "Photograph credit", exact: true })).toBeVisible()
  await page.keyboard.press("Escape")
  await expect(dialog.getByRole("region", { name: "Photograph credit", exact: true })).toBeHidden()
  await expect(credit).toBeFocused()
  await expect(dialog).toBeVisible()
  await page.keyboard.press("Escape")
  await expect(dialog).toHaveCount(0)
  await expect(expand).toBeFocused()
  await expect(photo).toHaveAttribute("src", src!)
  await expect(page.getByLabel("Landscape region", { exact: true })).toHaveValue("north-island")
  await expect.poll(async () => Math.abs(await page.evaluate(() => scrollY) - scroll)).toBeLessThanOrEqual(2)
})

test("player identity follows the chosen country and Escape returns to the active sound control", async ({ page }, info) => {
  test.skip(!["desktop", "phone-390"].includes(info.project.name), "Sound identity and return focus use desktop and phone without contacting external media providers.")
  await page.goto("/")
  await declineOptionalCookies(page)
  await page.getByRole("button", { name: "Turn to the birds", exact: true }).click()
  const listen = page.getByRole("button", { name: "Listen to bird call", exact: true })
  await listen.click()
  const player = page.getByRole("complementary", { name: "AVES travel media player", exact: true })
  await expect(player).toHaveAttribute("data-aves-media-country", "colombia")
  await expect(player).toContainText("Green-bearded Helmetcrest")
  await player.getByRole("button", { name: "Expand player", exact: true }).click()
  await player.getByRole("link", { name: /Recording source/ }).focus()
  await page.keyboard.press("Escape")
  await expect(player.getByRole("button", { name: "Expand player", exact: true })).toBeFocused()
  await page.keyboard.press("Escape")
  await expect(player).toHaveCount(0)
  await expect(listen).toBeFocused()
  await page.getByRole("group", { name: "Choose a country to preview", exact: true }).getByRole("button", { name: "New Zealand", exact: true }).click()
  await page.getByRole("button", { name: "Listen to bird call", exact: true }).click()
  await expect(player).toHaveAttribute("data-aves-media-country", "new-zealand")
  await expect(player).toContainText("Kea")
  await player.getByRole("button", { name: "Close player and stop playback", exact: true }).click()
  await expect(player).toHaveCount(0)
})

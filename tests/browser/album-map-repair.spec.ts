import {test,expect,declineOptionalCookies} from './public-fixture'

for (const path of ['/', '/australia', '/new-zealand/south-island']) {
 test(`album framing and map controls: ${path}`, async ({page}, info) => {
  test.setTimeout(90000)
  await page.goto(path)
  await declineOptionalCookies(page)
  const turn=page.getByRole('button',{name:'Turn to the birds',exact:true}).first()
  if(await turn.isVisible()) await turn.click()
  const frame=page.locator('[data-carousel-image]:visible').first()
  await expect(frame).toBeVisible()
  const photo=frame.locator('img').first()
  await expect.poll(()=>photo.evaluate((image:HTMLImageElement)=>image.complete&&image.naturalWidth>0)).toBe(true)
  await expect(photo).toHaveCSS('object-fit','contain')
  const box=await frame.boundingBox()
  expect(box!.width/box!.height).toBeCloseTo(3/2,1)
  const picker=page.getByRole('navigation',{name:'Choose a bird photograph'}).first()
  await expect(picker).toBeVisible()
  const choices=picker.getByRole('button')
  await choices.nth(1).click()
  await expect(choices.nth(1)).toHaveAttribute('aria-pressed','true')
  await expect(photo).toHaveCSS('object-fit','contain')
  await frame.screenshot({path:`test-results/album-${info.project.name}-${path.replaceAll('/','_')}.png`})
  await page.getByRole('button',{name:'Turn to the map',exact:true}).first().click()
  const map=page.locator('dialog[data-aves-map]:visible').first()
  const toolbar=map.locator('[data-map-controls]')
  const surface=map.locator('[data-map-surface]')
  const toolbarBox=await toolbar.boundingBox(),surfaceBox=await surface.boundingBox()
  expect(toolbarBox!.y).toBeGreaterThanOrEqual(surfaceBox!.y+surfaceBox!.height-1)
  await map.getByRole('button',{name:'Map layers',exact:true}).click()
  await map.getByRole('radio',{name:'Roads & cities',exact:true}).check()
  await expect(map.getByRole('button',{name:/^Zoom .* in$/}).first()).toBeVisible()
  await map.getByRole('button',{name:/^Zoom .* in$/}).first().click()
  await expect(map.getByRole('radio',{name:'Roads & cities',exact:true})).toBeChecked()
  await page.keyboard.press('Escape')
  await expect(map.getByRole('button',{name:'Map layers',exact:true})).toBeFocused()
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)).toBeLessThanOrEqual(1)
  await map.screenshot({path:`test-results/map-${info.project.name}-${path.replaceAll('/','_')}.png`})
 })
}


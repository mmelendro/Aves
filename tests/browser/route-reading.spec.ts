import {test, expect, declineOptionalCookies} from "./public-fixture"

test("route reading keeps historical accounts separate and opens a conservation reference on the map", async ({page}, info) => {
  test.skip(!["desktop", "phone-390"].includes(info.project.name), "Reading and map handoff on desktop and phone")
  await page.goto("/new-zealand/north-island")
  await declineOptionalCookies(page)
  const reading = page.getByRole("region", {name: "Route sources and conservation references", exact: true})
  await expect(reading).toContainText("Oscar Thomas")
  await expect(reading).toContainText("Published 2021-04-21. Historical account.")
  await expect(reading.getByRole("link", {name: /Tiritiri Matangi, Official route reference/})).toHaveAttribute("href", /doc\.govt\.nz/)

  await page.goto("/new-zealand/south-island")
  await expect(reading).toContainText("Sarah Mankelow")
  await expect(reading).toContainText("Published 2011-06-22. Historical account.")
  await reading.getByText("Conservation directory · South Island pilot", {exact: true}).click()
  await reading.getByRole("link", {name: /Show public reference on map.*Orokonui Ecosanctuary/}).click()
  const selected = page.getByRole("region", {name: "Selected public place", exact: true})
  await expect(selected.getByRole("status")).toHaveText("Orokonui Ecosanctuary")
  await expect(page).toHaveURL(/#south-island-bird-map$/)
  await expect(page.getByRole("button", {name: "Preview public place: Orokonui Ecosanctuary", exact: true})).toHaveAttribute("aria-pressed", "true")

  await reading.getByText("B Corp company directory · South Island pilot", {exact: true}).click()
  await reading.getByLabel("Type of business", {exact: true}).selectOption("accommodation")
  const company = reading.getByRole("article").filter({has: page.getByRole("heading", {name: "Lake Hāwea Station", exact: true})})
  await expect(company).toContainText("Certified company: Lake Hawea Station")
  await expect(company).toContainText("Company profile checked 2026-11-13")
  await company.getByRole("link", {name: /Show company reference on map/}).click()
  await expect(selected.getByRole("status")).toHaveText("Lake Hāwea Station")
  await expect(selected).toContainText("not accommodation entrance")
})

test("conservation directory actions select the correct Colombian and Australian planning regions", async ({page}, info) => {
  test.skip(!["desktop", "phone-390"].includes(info.project.name), "Directory handoff on desktop and phone")
  await page.goto("/colombia")
  await declineOptionalCookies(page)
  const gallery = page.getByRole("main").locator("#place-gallery")
  await expect(gallery).toHaveCount(1)
  await gallery.getByText("Conservation directory · reviewed regional references", {exact:true}).click()
  const dorado = gallery.getByRole("article").filter({has: page.getByRole("heading", {name: /El Dorado conservation area/})})
  await expect(dorado).toContainText("El Dorado Rainforest Resort")
  await dorado.getByRole("link", {name: /Show planning region/}).click()
  await expect(page).toHaveURL(/region=sierra-nevada-de-santa-marta/)
  await page.goto("/australia")
  await expect(gallery).toHaveCount(1)
  await gallery.getByText("Conservation directory · reviewed regional references", {exact:true}).click()
  const gluepot = gallery.getByRole("article").filter({has: page.getByRole("heading", {name:"BirdLife Australia Gluepot Reserve", exact:true})})
  await gluepot.getByRole("link", {name: /Show planning region/}).click()
  await expect(page).toHaveURL(/region=south-australia/)
})

const {test}=require('node:test')
const assert=require('node:assert/strict')
const {readFileSync}=require('node:fs')
const {resolve}=require('node:path')
const {createHash}=require('node:crypto')
const load=require('./helpers/load-ts.cjs')()
const {nzChecklistMedia}=load('content/new-zealand-checklist-media.ts')
const {newZealandChecklist}=load('content/new-zealand-checklist.ts')
const catalogue=require('../content/new-zealand-checklist-media.json')

test('private reference snapshot preserves valid parent IDs, original credits and exact local assets',()=>{
 const names=new Map(newZealandChecklist.map(b=>[b.id,b.scientificName]))
 assert.equal(nzChecklistMedia.size,362)
 assert.equal(catalogue.images.length,362)
 for(const image of catalogue.images){
  assert.equal(image.scientificName.split(/\s+/).slice(0,2).join(' '),names.get(image.id))
  assert.match(image.asset,/^\/images\/[a-zA-Z0-9/_\-.]+$/)
  assert.equal(createHash('sha256').update(readFileSync(resolve(__dirname,'../public'+image.asset))).digest('hex'),image.sha256)
  assert.ok(image.credit.creator && image.credit.license && image.credit.modifications)
  for(const key of ['sourceUrl','licenseUrl'])assert.equal(new URL(image.credit[key]).protocol,'https:')
 }
 assert.equal(newZealandChecklist.filter(b=>!nzChecklistMedia.has(b.id)).length,15)
 assert.ok(!nzChecklistMedia.has('nz-b09bf97ba22d'),'unidentified crane cannot borrow another species image')
})
test('reference controls cannot submit the planner or expose its URL to image/credit requests',()=>{
 const source=readFileSync(resolve(__dirname,'../components/new-zealand-checklist-photo.tsx'),'utf8')
 assert.match(source,/<button type="button"/)
 assert.match(source,/src=\{sitePath\(photo.asset\)\}/)
 assert.match(source,/referrerPolicy="no-referrer"/)
 assert.match(source,/rel="noreferrer"/)
 assert.doesNotMatch(source,/fetch\(|onChange|onSaved|onSubmit|localStorage|sessionStorage/)
 assert.match(source,/Image unavailable/)
 assert.match(source,/Illustration/)
})

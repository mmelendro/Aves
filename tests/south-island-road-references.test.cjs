const {test}=require('node:test')
const assert=require('node:assert/strict')
const load=require('./helpers/load-ts.cjs')()
const p=load('lib/south-island-trip-planner.ts')
const r=load('lib/south-island-road-references.ts')
const {componentHarness,nodes}=require('./helpers/component-harness.cjs')
const draft=overrides=>p.buildSouthIslandTrip({...p.defaultTripInput,days:2,startCity:'christchurch',endCity:'queenstown',...overrides})

test('road references retain named primary publishers, reviewed scope, unique corridors and gateway IDs',()=>{
 const keys=new Set()
 assert.equal(r.roadReferenceData.corridors.length,15)
 for(const c of r.roadReferenceData.corridors){
  assert.ok(p.gatewayById.has(c.fromId)&&p.gatewayById.has(c.toId))
  assert.ok(c.minutes>0&&Number.isInteger(c.minutes))
  const key=[c.fromId,c.toId].sort().join(':');assert.ok(!keys.has(key));keys.add(key)
  const ref=r.roadReference(c.fromId,c.toId)
  assert.ok(ref.publisher&&ref.stopPolicy);assert.equal(ref.reviewedAt,'2026-11-11')
  assert.equal(new URL(ref.url).protocol,'https:')
 }
 assert.equal(r.roadReference('arthurs-pass','dunedin'),null,'never invent a composite road time from geographic distance')
 assert.equal(r.roadReference('__proto__','christchurch'),null)
})
test('corridor lookup works in either direction and preserves source figures and stop policies',()=>{
 assert.equal(r.roadReference('christchurch','arthurs-pass').minutes,150)
 assert.equal(r.roadReference('arthurs-pass','christchurch').minutes,150)
 assert.equal(r.roadReference('queenstown','te-anau').minutes,120)
 assert.match(r.roadReference('queenstown','te-anau').stopPolicy,/rest stops included/)
 assert.equal(r.roadReference('queenstown','dunedin').minutes,265)
 assert.equal(r.roadTimeLabel(435),'7 h 15 min')
})
test('exact endpoint towns do not inherit road times for a different town in the same broad base',()=>{
 const wanaka=draft({startCity:'wanaka',endCity:'te-anau'})
 const context=p.tripTransferContext(wanaka,1)
 assert.equal(context.from.id,'wanaka');assert.equal(context.to.id,'te-anau');assert.equal(context.reference,null)
 assert.equal(p.tripRoadSummary(wanaka).unknown,1)
 assert.match(p.tripTransferUrl(wanaka,1),/W%C4%81naka/)
 const queenstown=draft({startCity:'queenstown',endCity:'te-anau'})
 assert.equal(p.tripTransferContext(queenstown,1).reference.minutes,120)
 assert.equal(p.tripRoadSummary(queenstown).reviewed,1)
 assert.equal(p.tripTransferContext(queenstown,0),null)
})
test('mixed reviewed and unknown transfers remain explicit and copied notes retain source provenance',()=>{
 const d=p.buildSouthIslandTrip({...p.defaultTripInput,days:7,startCity:'christchurch',endCity:'queenstown',areaId:'arthurs-pass',birdIds:[load('content/new-zealand-checklist.ts').selectableNzBirds.find(b=>b.commonName==='Kea').id]})
 const summary=p.tripRoadSummary(d)
 assert.equal(summary.total,2);assert.equal(summary.reviewed,1);assert.equal(summary.unknown,1)
 const text=p.tripDraftText(d)
 assert.match(text,/Road reference Christchurch to Arthur’s Pass: about 2 h 30 min/)
 assert.match(text,/https:\/\/www.doc.govt.nz/)
 assert.match(text,/Road time needs review: Arthur’s Pass to Queenstown/)
 assert.match(text,/not live conditions or exact stay addresses/)
})
test('the day card exposes source and current-condition links, flags long references and never prices a trip',()=>{
 const d=draft()
 const tree=componentHarness('components/trip-planner/trip-day-card.tsx','default',{id:'road-qa',draft:d,index:1,onChange(){}}).render()
 const text=JSON.stringify(tree)
 assert.match(text,/7 h 15 min/);assert.match(text,/Long driving reference/)
 assert.ok(nodes(tree).some(n=>n.type==='a'&&n.props.href===r.roadReferenceData.conditionsUrl))
 assert.ok(nodes(tree).some(n=>n.type==='a'&&n.props.href==='https://www.realnz.com/en/plan/driving-times/'))
 assert.match(text,/not exact stay addresses or live traffic/)
})

const {test}=require('node:test')
const assert=require('node:assert/strict')
test('selection resolver uses existing country, region and place IDs without marine fallback inland',async()=>{
 const {selectedHeaderProfile:profile}=await import('../lib/header-landscape.mjs')
 assert.equal(profile('colombia','llanos').water,'wetland')
 assert.equal(profile('australia','australian-capital-territory').water,'river')
 assert.equal(profile('australia','queensland').water,'lake')
 assert.equal(profile('new-zealand','north-island').terrain,'volcanic')
 assert.equal(profile('new-zealand','rakiura').terrain,'wooded-island')
 assert.equal(profile('new-zealand','south-island','mountains').water,'none')
 assert.equal(profile('new-zealand','south-island','forest-and-lakes').water,'lake')
 assert.equal(profile('new-zealand','south-island','southern-forest').water,'lake')
 assert.equal(profile('new-zealand','south-island','coast').water,'ocean')
 assert.equal(profile('new-zealand','south-island'),undefined,'published NZ composite stays the default')
 assert.equal(profile('australia','unknown').water,'none')
})

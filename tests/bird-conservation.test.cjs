const {test}=require('node:test')
const assert=require('node:assert/strict')
const load=require('./helpers/load-ts.cjs')()
const data=require('../content/bird-conservation.json')
const {birdConservation,filterConservationBirds,matchesBirdFilters,defaultBirdFilters}=load('lib/bird-conservation.ts')
const bird=name=>({scientificName:name})

test('origin and endemic filters follow the selected country while leaving saved targets intact',()=>{
 const {birdCountryOrigin}=load('lib/bird-conservation.ts')
 const kea={scientificName:'Nestor notabilis'}, unknown={scientificName:'Unknown scientificus'}
 const selected=[kea,unknown], before=structuredClone(selected)
 assert.equal(birdCountryOrigin(kea,'new-zealand'),'endemic')
 assert.equal(matchesBirdFilters(kea,{origin:'native',endemicOnly:true,status:'EN'},'new-zealand'),true)
 assert.equal(matchesBirdFilters(kea,{endemicOnly:true,status:'all'},'australia'),false)
 assert.equal(matchesBirdFilters(unknown,{origin:'unknown',endemicOnly:false,status:'unknown'},'colombia'),true)
 assert.equal(matchesBirdFilters(unknown,{origin:'native',endemicOnly:false,status:'all'},'colombia'),false)
 filterConservationBirds(selected,{origin:'native',endemicOnly:true,status:'EN'},'new-zealand')
 assert.deepEqual(selected,before)
 const {newZealandChecklist}=load('content/new-zealand-checklist.ts')
 const introduced=newZealandChecklist.find(b=>b.origin==='Introduced')
 assert.ok(introduced)
 assert.equal(matchesBirdFilters(introduced,{origin:'introduced',endemicOnly:false,status:'all'},'new-zealand'),true)
 assert.equal(matchesBirdFilters(introduced,{origin:'native',endemicOnly:false,status:'all'},'new-zealand'),false)
})

test('every photographed species has a dated, linked global status and unique species identity',()=>{
 const {destinationBirds}=load('content/destination-birds.ts')
 const names=new Set(Object.values(destinationBirds).flat().map(b=>b.scientificName.split(' ').slice(0,2).join(' ')))
 assert.equal(names.size,73)
 assert.equal(new Set(data.species.map(r=>r.scientificName)).size,data.species.length)
 for(const name of names){const row=birdConservation(bird(name));assert.ok(row,name);assert.notEqual(row.globalStatus,'unknown',name);assert.ok(row.statusSource?.startsWith('https://'),name);assert.equal(row.checkedAt,'2026-11-11');if(row.endemicTo)assert.ok(row.endemicSource,name)}
})
test('threatened is CR, EN or VU; national listings and global LC remain separate',()=>{
 const gouldian=bird('Chloebia gouldiae'),kea=bird('Nestor notabilis'),near=bird('Coeligena phalerata')
 assert.equal(birdConservation(gouldian).globalStatus,'LC')
 assert.equal(matchesBirdFilters(gouldian,{endemicOnly:false,status:'threatened'}),false)
 assert.equal(matchesBirdFilters(gouldian,{endemicOnly:true,status:'national-threatened'}),true)
 assert.equal(matchesBirdFilters(kea,{endemicOnly:true,status:'EN'}),true)
 assert.equal(matchesBirdFilters(near,{endemicOnly:false,status:'threatened'}),false)
 for(const name of ['Cyanoramphus malherbi','Nestor notabilis','Nestor meridionalis'])assert.equal(matchesBirdFilters(bird(name),{endemicOnly:false,status:'threatened'}),true)
})
test('unverified records never become Least Concern or threatened by default',()=>{
 const missing=bird('Unknown scientificus')
 assert.equal(matchesBirdFilters(missing,defaultBirdFilters),true)
 assert.equal(matchesBirdFilters(missing,{endemicOnly:false,status:'unknown'}),true)
 for(const status of ['LC','EN','threatened','national-threatened'])assert.equal(matchesBirdFilters(missing,{endemicOnly:false,status}),false)
 assert.equal(matchesBirdFilters(missing,{endemicOnly:true,status:'all'}),false)
})
test('country endemic origin covers every living endemic in the complete New Zealand checklist',()=>{
 const {newZealandChecklist}=load('content/new-zealand-checklist.ts')
 const endemics=newZealandChecklist.filter(b=>b.origin==='Endemic')
 for(const b of endemics)assert.equal(matchesBirdFilters(b,{endemicOnly:true,status:'all'}),true,b.scientificName)
 assert.ok(endemics.length>70)
 assert.equal(matchesBirdFilters(bird('Gymnorhina tibicen'),{endemicOnly:true,status:'all'}),false,'native Australia and New Guinea is not an Australian endemic')
 assert.equal(matchesBirdFilters(bird('Cardinalis phoeniceus'),{endemicOnly:true,status:'all'}),false,'Colombia/Venezuela specialist is not a Colombian endemic')
})
test('subspecies photographs receive explicit species-level status without replacing source profiles',()=>{
 const source={scientificName:'Gallirallus australis australis',image:'original.jpg'}
 assert.equal(birdConservation(source).scientificName,'Gallirallus australis')
 const filtered=filterConservationBirds([source],{endemicOnly:true,status:'VU'})
 assert.equal(filtered[0],source);assert.equal(source.scientificName,'Gallirallus australis australis')
})
test('conservation filters intersect the selected region and South Island habitat without expanding ranges',()=>{
 const {getDestinationRegionBirds}=load('content/destination-regions.ts')
 const {filterSouthIslandBirds}=load('content/south-island-ecosystems.ts')
 const source=getDestinationRegionBirds('new-zealand','south-island')
 const filtered=filterConservationBirds(filterSouthIslandBirds(source,'forest'),{endemicOnly:true,status:'EN'})
 assert.ok(filtered.some(b=>b.id==='nz-kea'))
 assert.ok(!filtered.some(b=>b.id==='nz-yellow-eyed-penguin'))
 assert.ok(filtered.every(b=>source.includes(b)))
 const nsw=filterConservationBirds(getDestinationRegionBirds('australia','new-south-wales'),{endemicOnly:true,status:'EN'})
 assert.equal(nsw.some(b=>b.id==='au-carnabys-black-cockatoo'),false)
})

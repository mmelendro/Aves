const {test}=require('node:test')
const assert=require('node:assert/strict')
const load=require('./helpers/load-ts.cjs')()
const {filterNzBirds, matchesNzOrigin, nzOriginGroup, nzOriginLabel}=load('lib/nz-bird-filters.ts')
const {newZealandChecklist:birds}=load('content/new-zealand-checklist.ts')
const options={query:'',origin:'all',selectedOnly:false,selected:[]}
test('source-backed origin groups include endemic birds within native without inventing unknowns',()=>{
 assert.equal(birds.filter(b=>matchesNzOrigin(b.origin,'native')).length,342)
 assert.equal(birds.filter(b=>matchesNzOrigin(b.origin,'endemic')).length,93)
 assert.equal(birds.filter(b=>matchesNzOrigin(b.origin,'introduced')).length,35)
 assert.equal(birds.filter(b=>matchesNzOrigin(b.origin,'unknown')).length,0)
 for(const origin of [undefined,'','Unresolved'])assert.equal(nzOriginGroup(origin),'unknown')
 assert.equal(nzOriginLabel(undefined),'Origin not confirmed')
})
test('search, origin and selection intersect without mutating hidden wishes',()=>{
 const endemic=birds.find(b=>b.origin==='Endemic'), introduced=birds.find(b=>b.origin==='Introduced')
 const selected=Object.freeze([endemic.id,introduced.id])
 const results=filterNzBirds(birds,{...options,selected,selectedOnly:true,origin:'native'})
 assert.deepEqual(results.map(b=>b.id),[endemic.id]);assert.equal(selected.length,2)
 assert.equal(filterNzBirds(birds,{...options,selected,selectedOnly:true,origin:'all'}).length,2)
 assert.equal(filterNzBirds(birds,{...options,selected:[],selectedOnly:true}).length,0)
})
test('accent-insensitive Māori and scientific searches retain original reference records',()=>{
 const bird=birds.find(b=>b.maoriName && /[āēīōū]/.test(b.maoriName))
 const plain=bird.maoriName.normalize('NFD').replace(/[\u0300-\u036f]/g,'')
 assert.ok(filterNzBirds(birds,{...options,query:plain}).includes(bird))
 assert.ok(filterNzBirds(birds,{...options,query:bird.scientificName}).includes(bird))
 assert.equal(filterNzBirds(birds,{...options,query:'no-such-bird-reference'}).length,0)
})

const {test}=require('node:test')
const assert=require('node:assert/strict')
const {readFileSync,existsSync}=require('node:fs')
const {createHash}=require('node:crypto')
const {resolve}=require('node:path')
const load=require('./helpers/load-ts.cjs')()
const {nzChecklistMedia}=load('content/new-zealand-checklist-media.ts')
const {newZealandChecklist}=load('content/new-zealand-checklist.ts')
const catalogue=require('../content/new-zealand-checklist-thumbnails.json')

test('reference media keeps living checklist IDs, per-file rights, local files and integrity',()=>{
 const birds=new Map(newZealandChecklist.map(b=>[b.id,b]))
 const seen=new Set()
 for(const image of catalogue.images){
  assert.ok(!seen.has(image.id));seen.add(image.id)
  assert.equal(image.scientificName,birds.get(image.id)?.scientificName)
  assert.match(image.asset,/^\/images\/checklist\/nz-[a-f0-9]+\.(jpg|jpeg|png|webp)$/)
  const file=resolve(__dirname,'../public'+image.asset)
  assert.ok(existsSync(file),image.id)
  assert.equal(createHash('sha256').update(readFileSync(file)).digest('hex'),image.sha256)
  assert.ok(image.creator && image.license && image.modifications)
  assert.match(image.sourceUrl,/^https:\/\/commons.wikimedia.org\/wiki\/File:/)
  assert.ok(image.license==='Public domain'||image.license==='CC0'||/creativecommons.org\/licenses\/by/.test(image.licenseUrl))
  assert.ok(!/-nc|-nd/.test(image.licenseUrl))
 }
 assert.ok(nzChecklistMedia.size>=345)
 assert.equal(nzChecklistMedia.get('unknown'),undefined)
 assert.ok(!nzChecklistMedia.has('nz-b09bf97ba22d'),'unidentified crane must not borrow a species photograph')
})
test('all living entries have a photo or an explicit pending slot; viewing remains separate from selection',()=>{
 const source=readFileSync(resolve(__dirname,'../components/new-zealand-bird-search.tsx'),'utf8')
 assert.match(source,/Image pending/)
 assert.match(source,/nzChecklistMedia\.has\(bird.id\) \? <NewZealandChecklistPhoto/)
 const viewer=readFileSync(resolve(__dirname,'../components/new-zealand-checklist-photo.tsx'),'utf8')
 assert.match(viewer,/width=\{64\} height=\{64\} loading="lazy"/)
 assert.match(viewer,/alt=""/)
 assert.doesNotMatch(viewer,/onChange|setSelected|toggle\(/)
 assert.match(viewer,/Image unavailable/)
 assert.match(viewer,/Illustration/)
})
